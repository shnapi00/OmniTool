use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=../.env");
    println!("cargo:rerun-if-env-changed=OMNITOOL_TG_TOKEN");
    println!("cargo:rerun-if-env-changed=VITE_DEFAULT_TG_BOT_TOKEN");

    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".into());
    let env_path = Path::new(&manifest_dir)
        .parent()
        .map(|p| p.join(".env"))
        .unwrap_or_else(|| PathBuf::from("../.env"));

    let mut token: Option<String> = std::env::var("OMNITOOL_TG_TOKEN")
        .ok()
        .or_else(|| std::env::var("VITE_DEFAULT_TG_BOT_TOKEN").ok());

    if token.as_deref().unwrap_or("").trim().is_empty() {
        if let Ok(content) = fs::read_to_string(&env_path) {
            for line in content.lines() {
                let line = line.trim();
                if line.is_empty() || line.starts_with('#') {
                    continue;
                }
                if let Some((k, v)) = line.split_once('=') {
                    let k = k.trim();
                    let v = v.trim().trim_matches('"').trim_matches('\'');
                    if (k == "OMNITOOL_TG_TOKEN" || k == "VITE_DEFAULT_TG_BOT_TOKEN") && !v.is_empty() {
                        token = Some(v.to_string());
                        break;
                    }
                }
            }
        }
    }

    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR not set");
    let dest_path = Path::new(&out_dir).join("embedded_token.rs");

    if let Some(tok) = token.filter(|t| !t.trim().is_empty()) {
        let trimmed = tok.trim();
        let token_bytes = trimmed.as_bytes();

        // Generate dynamic mask bytes
        let mut seed: u64 = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_nanos() as u64)
            .unwrap_or(0xA5A5A5A55A5A5A5A);
        seed ^= (std::process::id() as u64).wrapping_shl(32);

        let mut next_mask_byte = |index: usize| -> u8 {
            seed = seed.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
            let mut b = ((seed >> 33) ^ (seed >> 11)) as u8;
            if b == 0 {
                b = ((index as u8).wrapping_mul(37) ^ 0x5C) | 0x01;
            }
            b
        };

        let mut mask: Vec<u8> = Vec::with_capacity(token_bytes.len());
        let mut encrypted: Vec<u8> = Vec::with_capacity(token_bytes.len());

        for (i, &b) in token_bytes.iter().enumerate() {
            let m = next_mask_byte(i);
            mask.push(m);
            encrypted.push(b ^ m);
        }

        let generated_code = format!(
            "// Auto-generated by build.rs - DO NOT EDIT\n\
             pub const ENCRYPTED_TOKEN: &[u8] = &{:?};\n\
             pub const TOKEN_MASK: &[u8] = &{:?};\n\n\
             #[inline(never)]\n\
             pub fn get_default_token() -> String {{\n\
                 let decrypted: Vec<u8> = ENCRYPTED_TOKEN\n\
                     .iter()\n\
                     .zip(TOKEN_MASK.iter())\n\
                     .map(|(&c, &m)| c ^ m)\n\
                     .collect();\n\
                 String::from_utf8(decrypted).unwrap_or_default()\n\
             }}\n\n\
             pub fn has_default_token() -> bool {{\n\
                 !ENCRYPTED_TOKEN.is_empty()\n\
             }}\n",
            encrypted, mask
        );
        fs::write(&dest_path, generated_code).expect("Failed to write embedded_token.rs");
    } else {
        let generated_code = "// Auto-generated by build.rs - DO NOT EDIT (no token provided)\n\
             pub const ENCRYPTED_TOKEN: &[u8] = &[];\n\
             pub const TOKEN_MASK: &[u8] = &[];\n\n\
             pub fn get_default_token() -> String {\n\
                 String::new()\n\
             }\n\n\
             pub fn has_default_token() -> bool {\n\
                 false\n\
             }\n";
        fs::write(&dest_path, generated_code).expect("Failed to write embedded_token.rs");
    }

    tauri_build::build();
}
